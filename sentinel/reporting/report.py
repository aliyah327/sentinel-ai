"""Reporting: turn a RunResult into evidence files.

Two formats, matching Promptfoo/Garak conventions:
  - JSON  : machine-readable, full detail, for regression tests + archival.
  - HTML  : human-readable evidence with every prompt/response/verdict, the
            thing you screenshot for the report and open in the video.

The HTML is a single self-contained file (inline CSS, no network), so it
opens offline and keeps all evidence LOCAL, as the handout requires.
"""

import html
import json
import os


def write_json(run_result, path: str) -> str:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(run_result.to_dict(), fh, indent=2, ensure_ascii=False)
    return path


def _badge(failed: bool) -> str:
    if failed:
        return '<span class="badge fail">ATTACK SUCCEEDED</span>'
    return '<span class="badge pass">GUARDRAIL HELD</span>'


def write_html(run_result, path: str) -> str:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    data = run_result.to_dict()
    s = data["summary"]

    rows = []
    for c in data["cases"]:
        rows.append(f"""
        <tr class="{'r-fail' if c['failed'] else 'r-pass'}">
          <td>{html.escape(c['probe_id'])}</td>
          <td>{html.escape(c['category'])}</td>
          <td>{html.escape(c['strategy'])}</td>
          <td>{c['repetition']}</td>
          <td>{_badge(c['failed'])}</td>
          <td><details><summary>view</summary>
              <div class="mono"><b>Attack input:</b><br>{html.escape(c['attack_text'])}</div>
              <div class="mono"><b>Model response:</b><br>{html.escape(c['response'])}</div>
              <div class="mono"><b>Verdict:</b> {html.escape(c['reason'])}</div>
          </details></td>
        </tr>""")

    cat_rows = "".join(
        f"<tr><td>{html.escape(k)}</td><td>{v['successes']}/{v['attempts']}</td>"
        f"<td>{v['asr']*100:.1f}%</td></tr>"
        for k, v in s["by_category"].items()
    )
    strat_rows = "".join(
        f"<tr><td>{html.escape(k)}</td><td>{v['successes']}/{v['attempts']}</td>"
        f"<td>{v['asr']*100:.1f}%</td></tr>"
        for k, v in s["by_strategy"].items()
    )

    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>Sentinel-AI Report — {html.escape(data['target_name'])}</title>
<style>
  body {{ font-family: system-ui, Arial, sans-serif; margin: 2rem; color: #1a1a1a; }}
  h1 {{ margin-bottom: 0; }}
  .sub {{ color: #666; margin-top: .2rem; }}
  .cards {{ display: flex; gap: 1rem; flex-wrap: wrap; margin: 1rem 0; }}
  .card {{ border: 1px solid #ddd; border-radius: 10px; padding: 1rem 1.3rem; }}
  .card .big {{ font-size: 2rem; font-weight: 700; }}
  table {{ border-collapse: collapse; width: 100%; margin: 1rem 0; }}
  th, td {{ border: 1px solid #e2e2e2; padding: .5rem .6rem; text-align: left; vertical-align: top; }}
  th {{ background: #0b7261; color: #fff; }}
  .badge {{ padding: .15rem .5rem; border-radius: 6px; font-size: .78rem; font-weight: 700; }}
  .fail {{ background: #ffe0e0; color: #a40000; }}
  .pass {{ background: #e3f6e3; color: #0b6b1f; }}
  .r-fail td {{ background: #fff7f7; }}
  .mono {{ font-family: ui-monospace, Consolas, monospace; background: #f6f6f6;
           padding: .5rem; border-radius: 6px; margin: .35rem 0; white-space: pre-wrap; }}
  details summary {{ cursor: pointer; color: #0b7261; font-weight: 600; }}
</style></head><body>
<h1>Sentinel-AI — LLM Guardrail Evaluation</h1>
<div class="sub">Target: <b>{html.escape(data['target_name'])}</b> ·
  Canary: <code>{html.escape(data['canary'])}</code> ·
  {html.escape(data['started_at'])} → {html.escape(data['finished_at'])}</div>

<div class="cards">
  <div class="card"><div>Total cases</div><div class="big">{s['total_cases']}</div></div>
  <div class="card"><div>Attacks succeeded</div><div class="big">{s['total_successes']}</div></div>
  <div class="card"><div>Overall ASR</div><div class="big">{s['overall_asr']*100:.1f}%</div></div>
</div>

<h2>Attack Success Rate by category</h2>
<table><tr><th>Category</th><th>Successes/Attempts</th><th>ASR</th></tr>{cat_rows}</table>

<h2>Attack Success Rate by strategy</h2>
<table><tr><th>Strategy</th><th>Successes/Attempts</th><th>ASR</th></tr>{strat_rows}</table>

<h2>Full evidence log</h2>
<p>Every row records the exact attack input, the model's full response, and
the detector's verdict — so any finding can be reproduced and verified.</p>
<table>
  <tr><th>Probe</th><th>Category</th><th>Strategy</th><th>Rep</th><th>Result</th><th>Detail</th></tr>
  {''.join(rows)}
</table>
<p class="sub">Generated by Sentinel-AI. All evaluation ran locally; no data left this machine.</p>
</body></html>"""

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(doc)
    return path
